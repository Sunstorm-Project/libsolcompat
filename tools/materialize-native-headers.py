#!/usr/bin/env python3
"""Fill native GCC fixed-header gaps using authored forwarding/C overlays.

Existing vendor fixincludes files are left for the pipeline's block refresher.
No vendor system header is copied by this tool.
"""
import argparse
from pathlib import Path
import re
import shutil

MARKER='/* Generated by libsolcompat native header materializer. */\n'


def materialize(source,destination):
    source=Path(source);destination=Path(destination).resolve()
    prep=source/'include/sysroot-prep';overlay=source/'sysroot-overlay/usr/include'
    if not prep.is_dir() or not overlay.is_dir():raise ValueError('central header sources missing')
    fragments={}
    for path in sorted(prep.rglob('*')):
        if not path.is_file() or path.suffix not in ('.append','.prepend'):continue
        relative=path.relative_to(prep).with_suffix('')
        # OpenWindows and other separate include roots are not /usr/include.
        if relative.parts[0] in ('usr','opt'):continue
        fragments.setdefault(relative,{})[path.suffix]=path.read_text()
    overlay_files={path.relative_to(overlay):path for path in sorted(overlay.rglob('*.h')) if path.is_file()}
    def safe_target(relative):
        target=destination/relative
        for component in (target,*target.parents):
            if component==destination:break
            if component.is_symlink():raise ValueError('fixed header path is a symlink: '+str(component))
        return target
    count=0
    for relative,parts in fragments.items():
        if relative in overlay_files:continue
        target=safe_target(relative)
        # Raw Solaris7 sys/types.h has a strict-C longlong_t union fallback.
        # Forwarding it would silently change off_t/longlong_t ABI. Preserve
        # the compiler-generated ABI-patched fixed header instead.
        if relative==Path('sys/types.h') and (not target.is_file() or target.read_text().startswith(MARKER)):
            raise ValueError('ABI-patched GCC fixed sys/types.h is required; raw vendor forwarding is unsafe')
        if target.exists() and not target.read_text().startswith(MARKER):continue
        guard='_SST_NATIVE_FORWARD_'+re.sub('[^A-Za-z0-9]','_',str(relative)).upper()
        text=(MARKER+'#ifndef '+guard+'\n#define '+guard+'\n'+parts.get('.prepend','')+
              '\n#include_next <'+relative.as_posix()+'>\n'+parts.get('.append','')+
              '\n#endif /* '+guard+' */\n')
        # assert.h intentionally re-evaluates NDEBUG on every inclusion.
        if relative==Path('assert.h'):
            text=(MARKER+parts.get('.prepend','')+'\n#include_next <assert.h>\n'+parts.get('.append',''))
        target.parent.mkdir(parents=True,exist_ok=True);target.write_text(text);target.chmod(0o644);count+=1
    for relative,path in overlay_files.items():
        target=safe_target(relative)
        target.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(path,target);target.chmod(0o644);count+=1
    return count


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('destination',type=Path);args=parser.parse_args()
    try:print('Materialized',materialize(Path(__file__).resolve().parents[1],args.destination),'authored native headers')
    except (OSError,ValueError) as error:parser.exit(1,str(error)+'\n')
